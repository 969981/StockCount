#requires -Version 7.0
param(
    [ValidateSet('Debug','Release')][string]$Configuration = 'Release',
    [string]$OutputDirectory = 'publish/avalonia-desktop'
)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
Push-Location $root
try {
    if (-not [IO.Path]::IsPathFullyQualified($OutputDirectory)) {
        $OutputDirectory = Join-Path $root $OutputDirectory
    }
    $OutputDirectory = [IO.Path]::GetFullPath($OutputDirectory)
    New-Item -ItemType Directory -Force -Path $OutputDirectory | Out-Null
    $api = Join-Path $root 'src/StockCount.Api/StockCount.Api.csproj'
    $ui = Join-Path $root 'src/StockCount.Server.Desktop/StockCount.Server.Desktop.csproj'
    $apiStage = Join-Path $root 'publish/avalonia-api-stage'
    dotnet test tests/StockCount.Server.Hosting.Tests/StockCount.Server.Hosting.Tests.csproj -c $Configuration
    if ($LASTEXITCODE -ne 0) { throw 'Hosting tests failed.' }
    dotnet publish $api -c $Configuration -r win-x64 --self-contained true -o $apiStage
    if ($LASTEXITCODE -ne 0) { throw 'API publish failed.' }
    dotnet publish $ui -c $Configuration -r win-x64 --self-contained true -o $OutputDirectory
    if ($LASTEXITCODE -ne 0) { throw 'Avalonia desktop publish failed.' }
    Copy-Item (Join-Path $apiStage 'StockCount.Api.exe') -Destination (Join-Path $OutputDirectory 'StockCount.Api.exe') -Force
    if (!(Test-Path (Join-Path $OutputDirectory 'StockCount.Server.Desktop.exe'))) {
        throw 'Desktop EXE missing.'
    }
    if (!(Test-Path (Join-Path $OutputDirectory 'StockCount.Api.exe'))) {
        throw 'API EXE missing.'
    }
    Write-Host "Avalonia desktop prepared: $OutputDirectory"
    Write-Host 'Only executable/dependency files are published. Local JSON/SQLite/credentials are not generated by the build.'
} finally { Pop-Location }
